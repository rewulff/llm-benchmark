#!/usr/bin/env python3
"""Baseline tests for logfilter.py.

These cover the behaviour that existed before any extension and must keep
passing. Do not edit this file.
"""

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TOOL = os.path.join(HERE, "logfilter.py")
LOG = os.path.join(HERE, "sample.log")
sys.path.insert(0, HERE)


def run_cli(*args):
    """Run the CLI and return the completed process."""
    return subprocess.run(
        [sys.executable, TOOL, LOG, *args],
        capture_output=True,
        text=True,
    )


def out_lines(proc):
    return [line for line in proc.stdout.splitlines() if line.strip()]


def check(condition, message):
    if not condition:
        raise AssertionError(message)


def test_no_filter_returns_every_entry():
    proc = run_cli()
    check(proc.returncode == 0, f"exit {proc.returncode}, stderr: {proc.stderr.strip()}")
    lines = out_lines(proc)
    check(len(lines) == 15, f"got {len(lines)} lines without a filter, expected 15")


def test_level_filter():
    proc = run_cli("--level", "ERROR")
    check(proc.returncode == 0, f"exit {proc.returncode}, stderr: {proc.stderr.strip()}")
    lines = out_lines(proc)
    check(len(lines) == 3, f"got {len(lines)} ERROR lines, expected 3")
    check(all(" ERROR " in line for line in lines), "non-ERROR line in the output")


def test_unknown_level_is_rejected():
    proc = run_cli("--level", "TRACE")
    check(proc.returncode != 0, "unknown level was accepted")


def test_filter_lines_api():
    from logfilter import filter_lines, read_lines

    lines = read_lines(LOG)
    check(len(filter_lines(lines)) == 15, "filter_lines() without arguments must return everything")
    warns = filter_lines(lines, level="WARN")
    check(len(warns) == 3, f"filter_lines(level='WARN') returned {len(warns)}, expected 3")


TESTS = [
    test_no_filter_returns_every_entry,
    test_level_filter,
    test_unknown_level_is_rejected,
    test_filter_lines_api,
]


def main():
    failures = 0
    for test in TESTS:
        try:
            test()
        except Exception as exc:
            print(f"FAIL {test.__name__}: {type(exc).__name__}: {exc}")
            failures += 1
        else:
            print(f"ok   {test.__name__}")
    if failures:
        print(f"{failures} of {len(TESTS)} baseline tests failed")
        return 1
    print(f"all {len(TESTS)} baseline tests passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
