#!/usr/bin/env python3
"""End-to-end check for the readings pipeline.

The three stages run in order and the script stops at the FIRST failing stage,
so a single run only ever shows the next problem in the chain.

Do not edit this file — it defines the expected contract.
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, "sample.json")
sys.path.insert(0, HERE)

EXPECTED_RAW_READINGS = 8
EXPECTED_THRESHOLD = 20
EXPECTED_VALUES = [25, 31, 42, 27, 35]
EXPECTED_AVERAGE = 32.0
EXPECTED_REPORT = [
    "Report: sensor-a (celsius)",
    "1. 42",
    "2. 35",
    "3. 31",
    "selected=5 average=32.0",
]


def check(condition, message):
    """Raise AssertionError(message) if condition is falsy."""
    if not condition:
        raise AssertionError(message)


def stage_config(_previous=None):
    """Stage 1 — the config loader must expose name, threshold and readings."""
    from config_loader import load_config

    config = load_config(DATA)
    check(
        config["name"] == "sensor-a",
        f"config name is {config['name']!r}, expected 'sensor-a'",
    )
    check(
        config["threshold"] == EXPECTED_THRESHOLD,
        f"config threshold is {config['threshold']!r}, expected {EXPECTED_THRESHOLD!r}",
    )
    check(
        config["unit"] == "celsius",
        f"config unit is {config['unit']!r}, expected 'celsius'",
    )
    check(
        len(config["readings"]) == EXPECTED_RAW_READINGS,
        f"got {len(config['readings'])} raw readings, expected {EXPECTED_RAW_READINGS}",
    )
    return config


def stage_pipeline(config):
    """Stage 2 — the pipeline must filter and aggregate the readings."""
    from pipeline import summarize

    summary = summarize(config)
    check(
        summary["values"] == EXPECTED_VALUES,
        f"summary values are {summary['values']!r}, expected {EXPECTED_VALUES!r}",
    )
    check(
        summary["count"] == len(EXPECTED_VALUES),
        f"summary count is {summary['count']!r}, expected {len(EXPECTED_VALUES)}",
    )
    check(
        abs(summary["average"] - EXPECTED_AVERAGE) < 1e-9,
        f"summary average is {summary['average']!r}, expected {EXPECTED_AVERAGE!r}",
    )
    return summary


def stage_report(summary):
    """Stage 3 — the report must render header, top-3 ranking and footer."""
    from report import format_report

    text = format_report(summary)
    lines = text.splitlines()
    check(
        len(lines) == len(EXPECTED_REPORT),
        f"report has {len(lines)} lines, expected {len(EXPECTED_REPORT)}:\n{text}",
    )
    for got, want in zip(lines, EXPECTED_REPORT):
        check(got == want, f"report line is {got!r}, expected {want!r}")
    return text


STAGES = [
    ("config", stage_config),
    ("pipeline", stage_pipeline),
    ("report", stage_report),
]


def main():
    total = len(STAGES)
    carried = None
    for index, (name, stage) in enumerate(STAGES, start=1):
        try:
            carried = stage(carried)
        except Exception as exc:
            print(f"FAILED at stage {index}/{total} ({name}): {type(exc).__name__}: {exc}")
            print("Fix this stage first — the later stages have not run yet.")
            return 1
        print(f"ok   stage {index}/{total} ({name})")
    print(f"ALL {total} STAGES PASSED")
    return 0


if __name__ == "__main__":
    sys.exit(main())
